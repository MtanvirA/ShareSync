CREATE TABLE currency_exchange_rates (
    rate_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    from_currency  VARCHAR2(10) NOT NULL,
    to_currency    VARCHAR2(10) NOT NULL,
    exchange_rate  NUMBER(14,4) NOT NULL,
    effective_date DATE NOT NULL,
    source         VARCHAR2(100) NOT NULL,
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_currency_exchange_rates
        PRIMARY KEY (rate_id),

    CONSTRAINT uq_currency_exchange_rates
        UNIQUE (from_currency, to_currency, effective_date),

    CONSTRAINT ck_currency_exchange_rates_rate
        CHECK (exchange_rate > 0)
);
