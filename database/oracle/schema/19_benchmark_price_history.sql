-- Table: BENCHMARK_PRICE_HISTORY
-- Description: Stores time-series benchmark index values (DSEX, DS30, DSES).
-- ============================================================

CREATE TABLE benchmark_price_history (
    benchmark_price_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    benchmark_code             VARCHAR2(20)   NOT NULL,
    benchmark_name             VARCHAR2(100)  NOT NULL,
    trading_date               DATE           NOT NULL,
    close_value                NUMBER(14, 2)  NOT NULL,
    open_value                 NUMBER(14, 2),
    high_value                 NUMBER(14, 2),
    low_value                  NUMBER(14, 2),
    volume                     NUMBER(18, 0),
    source                     VARCHAR2(100)  DEFAULT 'Dhaka Stock Exchange' NOT NULL,
    source_dataset             VARCHAR2(255),
    source_doi                 VARCHAR2(100),
    created_at                 TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_benchmark_price_history PRIMARY KEY (benchmark_price_history_id),
    CONSTRAINT uq_bench_code_date UNIQUE (benchmark_code, trading_date),
    CONSTRAINT ck_bench_close CHECK (close_value > 0),
    CONSTRAINT ck_bench_open CHECK (open_value IS NULL OR open_value > 0),
    CONSTRAINT ck_bench_high CHECK (high_value IS NULL OR high_value > 0),
    CONSTRAINT ck_bench_low CHECK (low_value IS NULL OR low_value > 0),
    CONSTRAINT ck_bench_volume CHECK (volume IS NULL OR volume >= 0)
);

CREATE INDEX idx_bench_code_date ON benchmark_price_history (benchmark_code, trading_date);
